"""Generate schema.json and ts/index.ts from the Pydantic models (no network, no node).

Usage: python scripts/gen_ts.py [--check]   (--check exits 1 if committed output is stale)
"""

import json
import sys
from pathlib import Path

from pydantic import TypeAdapter

from ty_contracts import models

ROOT = Path(__file__).resolve().parent.parent
TOP = ["TripRequest", "PlanText", "Itinerary", "PlanEvent", "KathaStory", "GuideAnswer"]
HEADER = "// Generated by packages/contracts/scripts/gen_ts.py. Do not edit.\n\n"


def schema() -> dict:
    defs: dict = {}
    for name in TOP:
        s = TypeAdapter(getattr(models, name)).json_schema(mode="validation", ref_template="#/$defs/{model}")
        defs.update(s.pop("$defs", {}))
        defs[name] = s
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": dict(sorted(defs.items()))}


def ts(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(dict.fromkeys(ts(x) for x in s[key]))
    t = s.get("type")
    if t == "array":
        inner = ts(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" not in s:
            key = ts(s["propertyNames"]) if "propertyNames" in s else "string"
            return f"Partial<Record<{key}, {ts(s.get('additionalProperties') or {})}>>"
        req = set(s.get("required", []))
        body = "".join(
            f"  {json.dumps(k) if not k.isidentifier() else k}{'' if k in req else '?'}: {ts(v)};\n"
            for k, v in s["properties"].items()
        )
        return "{\n" + body + "}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def render() -> str:
    out = HEADER
    for name, s in schema()["$defs"].items():
        if "properties" in s:
            out += f"export interface {name} {ts(s)}\n\n"
        else:
            out += f"export type {name} = {ts(s)};\n\n"
    return out


def main() -> int:
    files = {
        ROOT / "schema.json": json.dumps(schema(), indent=2) + "\n",
        ROOT / "ts" / "index.ts": render(),
    }
    if "--check" in sys.argv:
        return 0 if all(p.exists() and p.read_text(encoding="utf-8") == c for p, c in files.items()) else 1
    for p, c in files.items():
        p.parent.mkdir(exist_ok=True)
        p.write_text(c, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
